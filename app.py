from pathlib import Path
import json
import joblib
import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

ROOT = Path(__file__).resolve().parent
MODEL_PATH = ROOT / "models" / "floodguard_demo_model.joblib"
METRICS_PATH = ROOT / "reports" / "demo_model_metrics.json"

st.set_page_config(
    page_title="FLOODGUARD AI | Research Prototype",
    page_icon="🌊",
    layout="wide"
)

@st.cache_resource
def load_model():
    if not MODEL_PATH.exists():
        from src.train_model import train
        train()
    return joblib.load(MODEL_PATH)

bundle = load_model()
model = bundle["model"]
features = bundle["features"]

st.title("🌊 FLOODGUARD AI")
st.caption("Flood-risk research prototype | Built for learning and research demonstration")

st.warning(
    "RESEARCH DEMO ONLY: The current model is trained on synthetic demonstration data. "
    "It is NOT trained or validated on live river, rainfall, or historical flood observations. "
    "Do not use this output for evacuation, emergency response, or real-world safety decisions."
)

left, right = st.columns([1.1, 0.9], gap="large")

with left:
    st.subheader("1. Enter environmental indicators")
    st.write("Use sample values to explore how the prototype behaves.")
    with st.form("risk_form"):
        location = st.text_input("Location label", "Patna (demo input)")
        rainfall_24h = st.slider("Rainfall in last 24 hours (mm)", 0.0, 250.0, 80.0, 1.0)
        rainfall_72h = st.slider("Rainfall in last 72 hours (mm)", 0.0, 500.0, 150.0, 1.0)
        river_level = st.slider("Observed river level (m)", 0.2, 8.0, 4.5, 0.1)
        river_capacity = st.slider("Reference river capacity (m)", 2.5, 7.0, 5.0, 0.1)
        soil = st.slider("Soil saturation (%)", 10.0, 100.0, 65.0, 1.0)
        elevation = st.slider("Elevation above local reference (m)", 0.0, 80.0, 15.0, 0.5)
        drainage = st.slider("Drainage score (0 poor – 100 good)", 0.0, 100.0, 40.0, 1.0)
        submitted = st.form_submit_button("Estimate demo risk", type="primary", use_container_width=True)

with right:
    st.subheader("2. Prototype output")
    if submitted:
        row = pd.DataFrame([{
            "rainfall_24h_mm": rainfall_24h,
            "rainfall_72h_mm": rainfall_72h,
            "river_level_m": river_level,
            "river_capacity_m": river_capacity,
            "soil_saturation_pct": soil,
            "elevation_m": elevation,
            "drainage_score": drainage,
        }], columns=features)
        probability = float(model.predict_proba(row)[0][1])
        label = "Higher model score" if probability >= 0.5 else "Lower model score"
        st.metric("Demo model score", f"{probability * 100:.1f}%")
        st.write(f"**Location label:** {location}")
        st.write(f"**Prototype category:** {label}")
        st.progress(min(max(probability, 0.0), 1.0))
        st.info(
            "This percentage is the demo model's output on synthetic training data. "
            "It is NOT a calibrated probability of a real flood."
        )
    else:
        st.info("Enter the values and press **Estimate demo risk** to see a demonstration output.")
        st.metric("Demo model score", "—")

st.divider()
st.subheader("3. How the model works")
st.write(
    "The prototype uses a Random Forest classifier. It receives seven input features "
    "and returns a model score for the synthetic label 'flood_within_24h'. "
    "The label was generated by a simple artificial rule for software testing."
)

if METRICS_PATH.exists():
    metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    st.subheader("4. Demo model evaluation")
    st.caption("These metrics are only for the synthetic teaching dataset.")
    cols = st.columns(4)
    for col, key, label in zip(
        cols, ["accuracy", "precision", "recall", "f1"],
        ["Accuracy", "Precision", "Recall", "F1 score"]
    ):
        col.metric(label, f"{metrics[key] * 100:.1f}%")
    st.error(
        "Do not interpret these numbers as real-world performance. "
        "A proper research version needs verified historical flood labels, "
        "time-based validation, location-based testing, and independent review."
    )

st.subheader("5. Next research steps")
st.markdown("""
- Replace synthetic data with verified, documented observations.
- Add river gauge levels, catchment boundaries, terrain and drainage data.
- Separate training and test periods chronologically to reduce data leakage.
- Compare baseline models and report precision/recall for flood events.
- Validate predictions on locations and dates never used in training.
""")

st.caption("FLOODGUARD AI | Student research prototype | Not an official warning system")
